package com.gokulsweets.restaurant.staff.approval;

/** Defines the supported approval request status values. */
public enum ApprovalRequestStatus {

    /** The pending value. */
    PENDING,
    /** The approved value. */
    APPROVED,
    /** The rejected value. */
    REJECTED,
    /** The sent back value. */
    SENT_BACK,
    /** The cancelled value. */
    CANCELLED
}
