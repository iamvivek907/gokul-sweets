package com.gokulsweets.restaurant.staff.approval;

/** Defines the supported approval request action values. */
public enum ApprovalRequestAction {

    /** The submitted value. */
    SUBMITTED,
    /** The approved value. */
    APPROVED,
    /** The rejected value. */
    REJECTED,
    /** The sent back value. */
    SENT_BACK,
    /** The resubmitted value. */
    RESUBMITTED,
    /** The cancelled value. */
    CANCELLED
}
