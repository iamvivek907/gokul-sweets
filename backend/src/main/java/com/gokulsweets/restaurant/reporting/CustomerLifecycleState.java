package com.gokulsweets.restaurant.reporting;

/** Defines the supported customer lifecycle state values. */
public enum CustomerLifecycleState {

    /** The new value. */
    NEW,
    /** The active value. */
    ACTIVE,
    /** The watch value. */
    WATCH,
    /** The at risk value. */
    AT_RISK,
    /** The lapsed value. */
    LAPSED,
    /** The reactivated value. */
    REACTIVATED
}
