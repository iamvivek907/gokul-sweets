package com.gokulsweets.restaurant.payment.enums;

/** Defines the supported payment status values. */
public enum PaymentStatus {

    /** The pending value. */
    PENDING,
    /** The paid value. */
    PAID,
    /** The failed value. */
    FAILED,
    /** The expired value. */
    EXPIRED,
    /** The refund pending value. */
    REFUND_PENDING,
    /** The refunded value. */
    REFUNDED,
    /** The refund failed value. */
    REFUND_FAILED
}
