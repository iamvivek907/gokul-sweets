package com.gokulsweets.restaurant.inventory.enums;

/** Defines the supported inventory reservation status values. */
public enum InventoryReservationStatus {

    /** The temporary hold value. */
    TEMPORARY_HOLD,
    /** The confirmed value. */
    CONFIRMED,
    /** The released value. */
    RELEASED,
    /** The expired value. */
    EXPIRED,
    /** The fulfilled value. */
    FULFILLED,
    /** The cancelled value. */
    CANCELLED
}
