/** Defines the supported preparation batch result values. */
public enum PreparationBatchResult {

    /** The started value. */
    STARTED,
    /** The already preparing value. */
    ALREADY_PREPARING,
    /** The not eligible value. */
    NOT_ELIGIBLE,
    /** The status changed value. */
    STATUS_CHANGED,
    /** The not found value. */
    NOT_FOUND,
    /** The branch mismatch value. */
    BRANCH_MISMATCH,
    /** The failed value. */
    FAILED
}
