-- Existing badges remain recognition-only until the owner explicitly configures a bonus.
CREATE TABLE customer_badges (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(80) NOT NULL,
 description VARCHAR(240) NOT NULL DEFAULT '',
 required_orders INTEGER NOT NULL CHECK(required_orders BETWEEN 1 AND 100000),
 minimum_subtotal NUMERIC(12,2) NOT NULL CHECK(minimum_subtotal BETWEEN 0 AND 1000000),
 bonus_percent NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK(bonus_percent BETWEEN 0 AND 100),
 appearance VARCHAR(12) NOT NULL DEFAULT 'GOLD' CHECK(appearance IN ('GOLD','SILVER','MAROON')),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 version INTEGER NOT NULL DEFAULT 1,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
