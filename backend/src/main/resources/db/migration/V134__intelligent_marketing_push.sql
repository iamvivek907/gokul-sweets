-- Promotional delivery is isolated from transactional order alerts. No branch is opted in on upgrade.
CREATE TABLE marketing_push_settings (
    environment VARCHAR(8) NOT NULL CHECK (environment IN ('DEV','PROD')),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    language VARCHAR(12) NOT NULL DEFAULT 'HINGLISH' CHECK (language IN ('EN','HINGLISH')),
    weekly_limit INTEGER NOT NULL DEFAULT 3 CHECK (weekly_limit BETWEEN 1 AND 3),
    lunch BOOLEAN NOT NULL DEFAULT TRUE,
    snacks BOOLEAN NOT NULL DEFAULT TRUE,
    dinner BOOLEAN NOT NULL DEFAULT TRUE,
    sweets BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(environment, branch_id)
);
CREATE TABLE marketing_push_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment VARCHAR(8) NOT NULL CHECK (environment IN ('DEV','PROD')),
    branch_id BIGINT NOT NULL REFERENCES branches(id),
    subject_id UUID NOT NULL,
    subscription_id UUID NOT NULL REFERENCES customer_push_subscriptions(id),
    send_date DATE NOT NULL,
    template_key VARCHAR(60) NOT NULL,
    topic VARCHAR(12) NOT NULL CHECK (topic IN ('LUNCH','SNACKS','DINNER','SWEETS')),
    title VARCHAR(80) NOT NULL,
    message VARCHAR(160) NOT NULL,
    reason VARCHAR(80) NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'QUEUED' CHECK (state IN ('QUEUED','SENDING','ACCEPTED','SKIPPED','FAILED','REVOKED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 3),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_token UUID,
    lease_until TIMESTAMPTZ,
    accepted_at TIMESTAMPTZ,
    last_http_status INTEGER,
    UNIQUE(environment, subject_id, send_date)
);
CREATE INDEX marketing_push_due ON marketing_push_deliveries(environment,next_attempt_at,id) WHERE state='QUEUED';
CREATE INDEX marketing_push_frequency ON marketing_push_deliveries(environment,subject_id,created_at DESC);
CREATE INDEX marketing_push_branch_history ON marketing_push_deliveries(environment,branch_id,id DESC);
