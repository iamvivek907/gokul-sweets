CREATE TABLE branch_meals (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 branch_id bigint NOT NULL REFERENCES branches(id),
 version bigint NOT NULL DEFAULT 1,
 title varchar(80) NOT NULL,
 title_hi varchar(120),
 description varchar(500),
 image_url varchar(600),
 base_price numeric(12,2) NOT NULL CHECK(base_price>0),
 discount_type varchar(10) NOT NULL CHECK(discount_type IN ('NONE','FIXED','PERCENT')),
 discount_value numeric(12,2) NOT NULL CHECK(discount_value>=0),
 estimated_cost numeric(12,2) CHECK(estimated_cost>=0),
 active boolean NOT NULL DEFAULT false,
 groups jsonb NOT NULL CHECK(jsonb_typeof(groups)='array'),
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX branch_meals_catalog ON branch_meals(branch_id,active,id);
