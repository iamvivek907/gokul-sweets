CREATE TABLE loyalty_holds (
 order_id BIGINT REFERENCES orders(id), generation INTEGER NOT NULL, environment VARCHAR(8) NOT NULL, subject_id UUID NOT NULL,
 reward_code VARCHAR(40) NOT NULL, coins INTEGER NOT NULL CHECK(coins>0), discount NUMERIC(12,2) NOT NULL,
 state VARCHAR(20) NOT NULL CHECK(state IN ('RESERVED','CONSUMED','RELEASED')), PRIMARY KEY(order_id,generation),
 FOREIGN KEY(environment,subject_id) REFERENCES loyalty_accounts(environment,subject_id)
);
CREATE TABLE loyalty_hold_lots (
 order_id BIGINT NOT NULL, generation INTEGER NOT NULL, ledger_id BIGINT REFERENCES loyalty_ledger(id),
 coins INTEGER NOT NULL CHECK(coins>0), PRIMARY KEY(order_id,generation,ledger_id), FOREIGN KEY(order_id,generation) REFERENCES loyalty_holds(order_id,generation)
);
CREATE OR REPLACE FUNCTION prevent_loyalty_ledger_mutation() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Loyalty ledger is append-only; use a compensating event'; END $$;
CREATE TRIGGER loyalty_ledger_immutable BEFORE UPDATE OR DELETE ON loyalty_ledger
 FOR EACH ROW EXECUTE FUNCTION prevent_loyalty_ledger_mutation();

