CREATE TABLE loyalty_ledger (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 environment VARCHAR(8) NOT NULL, subject_id UUID NOT NULL,
 event_key VARCHAR(160) NOT NULL, kind VARCHAR(30) NOT NULL, coins INTEGER NOT NULL,
 order_id BIGINT REFERENCES orders(id), source_credit_id BIGINT REFERENCES loyalty_ledger(id), reason VARCHAR(300) NOT NULL,
 expires_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(environment,subject_id,event_key),
 FOREIGN KEY(environment,subject_id) REFERENCES loyalty_accounts(environment,subject_id)
);
CREATE INDEX loyalty_ledger_owner ON loyalty_ledger(environment,subject_id,id);
CREATE INDEX loyalty_ledger_order_kind ON loyalty_ledger(order_id,kind) WHERE order_id IS NOT NULL;
-- Mutable projections; source of truth is the append-only ledger.
CREATE TABLE loyalty_lots (
